const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const sourceOrder = [
  'src/Config.gs',
  'src/CRM.gs',
  'src/Intake.gs',
  'src/FollowUp.gs',
  'src/Payments.gs',
  'src/Booking.gs',
  'src/Reminders.gs',
  'src/Prospects.gs',
  'src/Ops.gs',
  'src/Setup.gs',
  'src/Admin.gs',
  'src/BookingPage.gs',
  'src/WebApp.gs'
];
const banner = '// Generated by scripts/build-apps-script.js. Edit src/, not this file.\n\n';
const output = banner + sourceOrder.map((file) => {
  const body = fs.readFileSync(path.join(root, file), 'utf8').trimEnd();
  return '// ---- ' + file + ' ----\n' + body;
}).join('\n\n') + '\n';
const target = path.join(root, 'dist/Code.gs');

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== output) {
    console.error('dist/Code.gs is out of date. Run node scripts/build-apps-script.js');
    process.exit(1);
  }
  console.log('Apps Script bundle is current');
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, output);
  console.log('Wrote dist/Code.gs');
}

